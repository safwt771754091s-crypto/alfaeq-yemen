// وحدات عامة احتياطية حسب المرحلة عند غياب بيانات تفصيلية
function fallbackUnits(grade, subjectId) {
  const subject = SUBJECTS[subjectId];
  const nm = subject ? subject.name : 'المادة';
  if (grade <= 4) {
    return [
      C(`أساسيات ${nm}`, ['درس تمهيدي', 'المفاهيم الأولى', 'تدريبات وأمثلة']),
      C(`تطبيقات ${nm}`, ['أنشطة صفية', 'تدريبات عملية', 'تقويم الوحدة'])
    ];
  }
  if (grade <= 9) {
    return [
      C(`الوحدة الأولى: ${nm}`, ['مدخل الوحدة', 'المفاهيم الأساسية', 'التطبيقات', 'تقويم الوحدة']),
      C(`الوحدة الثانية: ${nm}`, ['تمهيد', 'المحتوى', 'أنشطة', 'تقويم']),
      C(`الوحدة الثالثة: ${nm}`, ['مراجعة', 'تطبيقات متقدمة', 'تقويم ختامي'])
    ];
  }
  return [
    C(`الوحدة الأولى: ${nm}`, ['مقدمة', 'المفاهيم الأساسية', 'التحليل', 'تقويم الوحدة']),
    C(`الوحدة الثانية: ${nm}`, ['تمهيد', 'الدراسة التفصيلية', 'تطبيقات', 'تقويم']),
    C(`الوحدة الثالثة: ${nm}`, ['مراجعة شاملة', 'مسائل وتطبيقات', 'تقويم نهائي'])
  ];
}

export function getUnits(grade, subjectId) {
  const key = `${subjectId}:${grade}`;
  // وحدات مستوردة من كتب المنهج (عدن) — تُقدَّم أولاً لأنها محتوى حقيقي مقروء.
  const imported = importedUnitsFor(grade, subjectId);
  const base = unitsFromSources(grade, subjectId, key);
  if (imported) return [...imported.map((u) => ({ ...u, sourced: true, imported: true })), ...base];
  return base;
}

function unitsFromSources(grade, subjectId, key) {
  // محتوى منهجي حقيقي مُجمَّع من مصادر مفتوحة (إن وُجد) — يُقدَّم أولاً
  const sourced = SOURCED_UNITS[key];
  if (sourced) {
    const withFlag = sourced.map((u) => ({ ...u, sourced: true }));
    if (CURRICULUM[key]) return [...withFlag, ...CURRICULUM[key]];
    return withFlag;
  }
  if (CURRICULUM[key]) return CURRICULUM[key];
  // ابحث عن أقرب صف له نفس المادة لتقديم محتوى أقرب للمنهج
  const gradesWithSubject = Object.keys(CURRICULUM)
    .filter((k) => k.startsWith(`${subjectId}:`))
    .map((k) => Number(k.split(':')[1]));
  if (gradesWithSubject.length) {
    const nearest = gradesWithSubject.reduce((a, b) =>
      Math.abs(b - grade) < Math.abs(a - grade) ? b : a
    );
    if (Math.abs(nearest - grade) <= 1) return CURRICULUM[`${subjectId}:${nearest}`];
  }
  return fallbackUnits(grade, subjectId);
}

export function getLessons(grade, subjectId) {
  return getUnits(grade, subjectId).flatMap((u) =>
    u.lessons.map((l) => ({ unit: u.title, lesson: l }))
  );
}

