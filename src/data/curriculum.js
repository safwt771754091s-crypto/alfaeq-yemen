// نظام الدرجات: من 100، النجاح 50 (المعتمد في معظم مدارس اليمن الأساسية/الثانوية)
export function estimateLabel(pct) {
  if (pct >= 90) return { label: 'ممتاز', grade: 'أ', color: 'emerald' };
  if (pct >= 80) return { label: 'جيد جداً', grade: 'ب', color: 'teal' };
  if (pct >= 70) return { label: 'جيد', grade: 'ج', color: 'sky' };
  if (pct >= 60) return { label: 'مقبول', grade: 'د', color: 'amber' };
  if (pct >= 50) return { label: 'ضعيف', grade: 'هـ', color: 'orange' };
  return { label: 'راسب', grade: 'و', color: 'rose' };
}

